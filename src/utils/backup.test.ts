import { describe, expect, it } from 'vitest';
import type { Opportunity } from '../types/opportunity';
import {
  makeActivity,
  makeContact,
  makeInterview,
  makeMaterial,
  makeOpportunity,
} from '../test/fixtures';
import {
  MAX_BACKUP_RECORDS,
  commitBackupImport,
  parseBackupJson,
  planImport,
  type ParsedBackup,
} from './backup';
import { createJsonBackup } from './exports';

const minimalRecord = {
  id: 'legacy-1',
  title: 'Legacy Role',
  company: 'Legacy Co.',
  type: 'Full-time',
  status: 'Saved',
};

function parseOk(text: string): ParsedBackup {
  const result = parseBackupJson(text);
  if (!result.ok) throw new Error(`Expected a valid backup: ${result.error.message}`);
  return result.backup;
}

function envelope(overrides: Record<string, unknown> = {}): Record<string, unknown> {
  return {
    ...JSON.parse(createJsonBackup([])),
    ...overrides,
  };
}

describe('parseBackupJson', () => {
  it('accepts a backup generated by the current exporter', () => {
    const items = [
      makeOpportunity({
        id: 'current-1',
        title: 'Frontend Engineer',
        company: 'Northwind Labs',
        priority: 'High',
        tags: ['Remote', 'React'],
        deadline: '2028-02-29',
        followUpDate: '2028-03-01',
        activities: [makeActivity({ id: 'activity-1' })],
        notes: 'Keep this.',
        isDemo: true,
      }),
    ];

    const result = parseBackupJson(createJsonBackup(items));

    expect(result.ok).toBe(true);
    if (!result.ok) return;
    expect(result.backup.records).toEqual(items);
    expect(result.backup.totalRecords).toBe(1);
    expect(result.backup.validRecords).toBe(1);
    expect(result.backup.repairedRecords).toBe(0);
    expect(result.backup.invalidRecords).toBe(0);
    expect(result.backup.duplicateRecords).toBe(0);
    expect(result.backup.exportedAt).toBeTruthy();
  });

  it('preserves valid archive metadata and treats legacy or malformed records as active', () => {
    const archivedAt = '2026-03-04T09:30:00.000Z';
    const archived = makeOpportunity({ id: 'archived', status: 'Applied', archivedAt });
    const active = makeOpportunity({ id: 'active' });
    const result = parseBackupJson(
      JSON.stringify(
        envelope({
          opportunities: [
            archived,
            active,
            { ...active, id: 'malformed', archivedAt: 'not-a-timestamp' },
          ],
        }),
      ),
    );

    expect(result.ok).toBe(true);
    if (!result.ok) return;
    expect(result.backup.validRecords).toBe(3);
    expect(result.backup.invalidRecords).toBe(0);
    expect(result.backup.repairedRecords).toBe(1);
    expect(result.backup.records[0].archivedAt).toBe(archivedAt);
    expect(result.backup.records[0].status).toBe('Applied');
    expect(result.backup.records[1].archivedAt).toBeUndefined();
    expect(result.backup.records[2].archivedAt).toBeUndefined();
  });

  it('gives a pre-interview backup empty workspace collections', () => {
    const result = parseBackupJson(JSON.stringify(envelope({ opportunities: [minimalRecord] })));

    expect(result.ok).toBe(true);
    if (!result.ok) return;
    expect(result.backup.records[0].interviews).toEqual([]);
    expect(result.backup.records[0].contacts).toEqual([]);
    expect(result.backup.records[0].materials).toEqual([]);
  });

  it('round-trips interviews, contacts, materials and stable IDs through export and parsing', () => {
    const contact = makeContact({ id: 'contact-7', name: 'Jordan Lee', role: 'Recruiter' });
    const interview = makeInterview({
      id: 'round-1',
      round: 'Hiring Manager Interview',
      date: '2026-03-04',
      time: '14:30',
      mode: 'In person',
      status: 'Completed',
      outcome: 'Positive',
      meetingUrl: 'https://meet.example.com/abc',
      location: 'Northwind HQ',
      preparationNotes: 'Review the team charter.',
      notes: 'Discussed the role scope.',
      contactId: 'contact-7',
    });
    const material = makeMaterial({
      id: 'material-7',
      label: 'Portfolio',
      kind: 'Portfolio',
      version: 'Updated October',
      status: 'Submitted',
    });
    const item = makeOpportunity({
      id: 'with-workspace',
      interviews: [interview],
      contacts: [contact],
      materials: [material],
    });

    const parsed = parseOk(createJsonBackup([item]));

    expect(parsed.records).toEqual([item]);
    expect(parsed.repairedRecords).toBe(0);
    expect(parsed.records[0].interviews[0].id).toBe('round-1');
    expect(parsed.records[0].interviews[0].contactId).toBe('contact-7');
    expect(parsed.records[0].contacts[0].id).toBe('contact-7');
    expect(parsed.records[0].materials[0].id).toBe('material-7');
  });

  it('repairs missing contact links while preserving interview history in imports', () => {
    const orphaned = makeInterview({
      id: 'round-1',
      round: 'Technical Interview',
      contactId: 'missing-contact',
      status: 'Completed',
      notes: 'Keep this history.',
    });
    const result = parseBackupJson(
      JSON.stringify(envelope({ opportunities: [makeOpportunity({ interviews: [orphaned] })] })),
    );

    expect(result.ok).toBe(true);
    if (!result.ok) return;
    expect(result.backup.repairedRecords).toBe(1);
    expect(result.backup.records[0].interviews[0]).toMatchObject({
      id: 'round-1',
      contactId: '',
      status: 'Completed',
      notes: 'Keep this history.',
    });
  });

  it('skips malformed contacts and materials without losing the parent opportunity', () => {
    const validContact = makeContact({ id: 'valid-contact' });
    const validMaterial = makeMaterial({ id: 'valid-material' });
    const parent = {
      ...makeOpportunity({ id: 'workspace-parent', notes: 'Keep this.' }),
      contacts: [validContact, { id: 'no-name', name: '' }],
      materials: [validMaterial, { id: 'no-label', label: '' }],
    };
    const result = parseBackupJson(
      JSON.stringify(envelope({ opportunities: [parent] })),
    );

    expect(result.ok).toBe(true);
    if (!result.ok) return;
    expect(result.backup.validRecords).toBe(1);
    expect(result.backup.invalidRecords).toBe(0);
    expect(result.backup.repairedRecords).toBe(1);
    expect(result.backup.records[0]).toMatchObject({
      id: 'workspace-parent',
      notes: 'Keep this.',
      contacts: [validContact],
      materials: [validMaterial],
    });
  });

  it('repairs or skips malformed imported interviews without losing the parent', () => {
    const valid = makeInterview({ id: 'valid-round' });
    const parent = {
      ...makeOpportunity({ id: 'interview-parent' }),
      interviews: [
        valid,
        { id: 'valid-round', round: 'Duplicate round', date: '2026-01-20' },
        { id: 'bad-date', round: 'Bad date', date: '2026-02-30' },
        { id: 'no-round', round: '', date: '2026-01-20' },
        null,
      ],
    };
    const result = parseBackupJson(
      JSON.stringify(
        envelope({
          opportunities: [parent],
        }),
      ),
    );

    expect(result.ok).toBe(true);
    if (!result.ok) return;
    expect(result.backup.validRecords).toBe(1);
    expect(result.backup.repairedRecords).toBe(1);
    expect(result.backup.invalidRecords).toBe(0);
    expect(result.backup.records[0]).toMatchObject({
      id: 'interview-parent',
      interviews: [valid],
    });
  });

  it('rejects invalid JSON and arbitrary JSON values', () => {
    expect(parseBackupJson('{not-json')).toMatchObject({
      ok: false,
      error: { code: 'invalid-json' },
    });
    expect(parseBackupJson(JSON.stringify([makeOpportunity()]))).toMatchObject({
      ok: false,
      error: { code: 'invalid-envelope' },
    });
    expect(parseBackupJson('null')).toMatchObject({
      ok: false,
      error: { code: 'invalid-envelope' },
    });
  });

  it('rejects the wrong format and missing or wrongly typed envelope fields', () => {
    expect(parseBackupJson(JSON.stringify(envelope({ format: 'something-else' })))).toMatchObject({
      ok: false,
      error: { code: 'invalid-envelope' },
    });
    expect(parseBackupJson(JSON.stringify(envelope({ format: undefined })))).toMatchObject({
      ok: false,
      error: { code: 'invalid-envelope' },
    });
    expect(parseBackupJson(JSON.stringify(envelope({ schemaVersion: '1' })))).toMatchObject({
      ok: false,
      error: { code: 'invalid-envelope' },
    });
    expect(parseBackupJson(JSON.stringify(envelope({ opportunities: {} })))).toMatchObject({
      ok: false,
      error: { code: 'invalid-envelope' },
    });
    expect(parseBackupJson(JSON.stringify(envelope({ opportunities: undefined })))).toMatchObject({
      ok: false,
      error: { code: 'invalid-envelope' },
    });
  });

  it('rejects unsupported schema versions', () => {
    const result = parseBackupJson(JSON.stringify(envelope({ schemaVersion: 2 })));

    expect(result.ok).toBe(false);
    if (result.ok) return;
    expect(result.error.code).toBe('unsupported-schema');
    expect(result.error.message).toContain('2');
    expect(result.error.message).toContain('1');
  });

  it('rejects excessive record counts before normalizing them', () => {
    const result = parseBackupJson(
      JSON.stringify(envelope({ opportunities: Array.from({ length: MAX_BACKUP_RECORDS + 1 }) })),
    );

    expect(result).toMatchObject({ ok: false, error: { code: 'too-many-records' } });
  });

  it('ignores malformed optional exportedAt metadata without weakening record validation', () => {
    const item = makeOpportunity({ id: 'valid-meta' });
    const result = parseBackupJson(
      JSON.stringify(envelope({ exportedAt: 42, opportunities: [item, null] })),
    );

    expect(result.ok).toBe(true);
    if (!result.ok) return;
    expect(result.backup.exportedAt).toBeNull();
    expect(result.backup.records).toEqual([item]);
    expect(result.backup.invalidRecords).toBe(1);
  });

  it('keeps valid siblings and reports invalid parent records', () => {
    const valid = makeOpportunity({ id: 'valid' });
    const backup = envelope({
      opportunities: [
        null,
        'not a record',
        { ...minimalRecord, id: '' },
        { ...minimalRecord, id: 'no-title', title: '   ' },
        { ...minimalRecord, id: 'no-company', company: '' },
        { ...minimalRecord, id: 'bad-type', type: 'Contract' },
        { ...minimalRecord, id: 'bad-status', status: 'Ghosted' },
        valid,
      ],
    });

    const result = parseBackupJson(JSON.stringify(backup));

    expect(result.ok).toBe(true);
    if (!result.ok) return;
    expect(result.backup.totalRecords).toBe(8);
    expect(result.backup.validRecords).toBe(1);
    expect(result.backup.records).toEqual([valid]);
    expect(result.backup.invalidRecords).toBe(7);
    expect(result.backup.duplicateRecords).toBe(0);
    expect(result.backup.skipped).toHaveLength(7);
    expect(result.backup.skipped.map((skip) => skip.reason)).toEqual(
      expect.arrayContaining([
        'Record is not an object.',
        'Missing a usable ID.',
        'Missing a title.',
        'Missing a company or client.',
        'Invalid opportunity type.',
        'Invalid opportunity status.',
      ]),
    );
  });

  it('repairs malformed optional fields and preserves the rest of the record', () => {
    const activity = makeActivity({ id: 'valid-activity' });
    const result = parseBackupJson(
      JSON.stringify(
        envelope({
          opportunities: [
            {
              ...minimalRecord,
              priority: 'Urgent',
              tags: [' Remote ', 'remote', 42, '', '  '],
              url: 42,
              deadline: '2026-02-30',
              followUpDate: 'not-a-date',
              activities: [activity, { id: '', type: 'Other', date: '2026-01-01' }],
              compensation: null,
              description: 42,
              notes: null,
              isDemo: 'yes',
            },
          ],
        }),
      ),
    );

    expect(result.ok).toBe(true);
    if (!result.ok) return;
    expect(result.backup.repairedRecords).toBe(1);
    expect(result.backup.invalidRecords).toBe(0);
    expect(result.backup.records[0]).toMatchObject({
      ...minimalRecord,
      priority: 'Medium',
      tags: ['Remote'],
      url: '',
      deadline: '',
      followUpDate: '',
      activities: [activity],
      compensation: '',
      description: '',
      notes: '',
    });
    expect(result.backup.records[0].isDemo).toBeUndefined();
  });

  it('keeps the first valid duplicate ID and skips later duplicates', () => {
    const first = makeOpportunity({ id: 'dup', title: 'First record' });
    const second = makeOpportunity({ id: 'dup', title: 'Second record' });
    const result = parseBackupJson(
      JSON.stringify(envelope({ opportunities: [first, second] })),
    );

    expect(result.ok).toBe(true);
    if (!result.ok) return;
    expect(result.backup.records).toHaveLength(1);
    expect(result.backup.records[0].title).toBe('First record');
    expect(result.backup.duplicateRecords).toBe(1);
    expect(result.backup.invalidRecords).toBe(0);
    expect(result.backup.skipped[0]).toMatchObject({ index: 1, id: 'dup' });
  });

  it('allows a later valid record to use an ID whose earlier record was invalid', () => {
    const invalid = { ...makeOpportunity({ id: 'same-id' }), title: '' };
    const valid = makeOpportunity({ id: 'same-id', title: 'Recovered record' });
    const result = parseBackupJson(
      JSON.stringify(envelope({ opportunities: [invalid, valid] })),
    );

    expect(result.ok).toBe(true);
    if (!result.ok) return;
    expect(result.backup.invalidRecords).toBe(1);
    expect(result.backup.duplicateRecords).toBe(0);
    expect(result.backup.records).toEqual([valid]);
  });

  it('distinguishes a valid empty backup from an all-invalid backup', () => {
    const empty = parseOk(JSON.stringify(envelope({ opportunities: [] })));
    expect(empty).toMatchObject({ totalRecords: 0, validRecords: 0, invalidRecords: 0 });

    const allInvalid = parseOk(JSON.stringify(envelope({ opportunities: [null, {}] })));
    expect(allInvalid).toMatchObject({ totalRecords: 2, validRecords: 0, invalidRecords: 2 });
  });
});

describe('planImport', () => {
  const currentA = makeOpportunity({ id: 'a', title: 'Current A' });
  const currentB = makeOpportunity({ id: 'b', title: 'Current B' });

  it('merges new IDs without overwriting existing records', () => {
    const incomingB = makeOpportunity({ id: 'b', title: 'Incoming B' });
    const incomingC = makeOpportunity({ id: 'c', title: 'Incoming C' });
    const backup = parseOk(JSON.stringify(envelope({ opportunities: [incomingB, incomingC] })));
    const current = [currentA, currentB];
    const snapshot = [...current];

    const plan = planImport(current, backup, 'merge');

    expect(plan.candidate.map((item) => item.id)).toEqual(['a', 'b', 'c']);
    expect(plan.candidate[1]).toBe(currentB);
    expect(plan.added).toBe(1);
    expect(plan.skippedExisting).toBe(1);
    expect(plan.replaced).toBe(0);
    expect(plan.finalCount).toBe(3);
    expect(current).toEqual(snapshot);
  });

  it('retains nested workspace data when merging and replacing', () => {
    const contact = makeContact({ id: 'contact-1' });
    const material = makeMaterial({ id: 'material-1' });
    const interview = makeInterview({ id: 'round-1', contactId: 'contact-1' });
    const incoming = makeOpportunity({
      id: 'workspace',
      contacts: [contact],
      materials: [material],
      interviews: [interview],
    });
    const backup = parseOk(createJsonBackup([incoming]));

    expect(planImport([currentA], backup, 'merge').candidate).toEqual([currentA, incoming]);
    expect(planImport([currentA], backup, 'replace').candidate).toEqual([incoming]);
  });

  it('preserves archive state in both merge and replace plans', () => {
    const archivedAt = '2026-03-04T09:30:00.000Z';
    const currentArchived = makeOpportunity({ id: 'current-archived', archivedAt });
    const incomingArchived = makeOpportunity({ id: 'incoming-archived', archivedAt });
    const backup = parseOk(createJsonBackup([incomingArchived]));

    expect(planImport([currentArchived], backup, 'merge').candidate).toEqual([
      currentArchived,
      incomingArchived,
    ]);
    expect(planImport([currentArchived], backup, 'replace').candidate).toEqual([
      incomingArchived,
    ]);
    expect(planImport([currentArchived], backup, 'replace').candidate[0].archivedAt).toBe(
      archivedAt,
    );
  });

  it('replaces with only valid normalized unique incoming records', () => {
    const incomingC = makeOpportunity({ id: 'c' });
    const backup = parseOk(
      JSON.stringify(envelope({ opportunities: [incomingC, null, { ...incomingC, title: '' }] })),
    );

    const plan = planImport([currentA, currentB], backup, 'replace');

    expect(plan.candidate).toEqual([incomingC]);
    expect(plan.replaced).toBe(2);
    expect(plan.finalCount).toBe(1);
    expect(plan.added).toBe(1);
  });

  it('handles an intentional empty replacement explicitly', () => {
    const backup = parseOk(JSON.stringify(envelope({ opportunities: [] })));
    const plan = planImport([currentA, currentB], backup, 'replace');

    expect(plan.candidate).toEqual([]);
    expect(plan.replaced).toBe(2);
    expect(plan.finalCount).toBe(0);
  });

  it('does not mutate either input collection', () => {
    const incoming = makeOpportunity({ id: 'new' });
    const backup = parseOk(JSON.stringify(envelope({ opportunities: [incoming] })));
    const current = [currentA];
    const currentSnapshot = [...current];
    const recordsSnapshot = [...backup.records];

    planImport(current, backup, 'merge');

    expect(current).toEqual(currentSnapshot);
    expect(backup.records).toEqual(recordsSnapshot);
  });
});

describe('commitBackupImport', () => {
  const current = [makeOpportunity({ id: 'existing' })];

  it('writes the candidate before returning it for a state update', () => {
    const incoming = makeOpportunity({ id: 'incoming' });
    const backup = parseOk(JSON.stringify(envelope({ opportunities: [incoming] })));
    let saved: Opportunity[] | null = null;

    const result = commitBackupImport(current, backup, 'merge', (items) => {
      saved = items;
      return true;
    });

    expect(result.ok).toBe(true);
    if (!result.ok) return;
    expect(saved).toEqual(result.plan.candidate);
    expect(result.plan.candidate.map((item) => item.id)).toEqual(['existing', 'incoming']);
    expect(current.map((item) => item.id)).toEqual(['existing']);
  });

  it('reports a failed write without mutating current records', () => {
    const backup = parseOk(JSON.stringify(envelope({ opportunities: [makeOpportunity({ id: 'new' })] })));

    const result = commitBackupImport(current, backup, 'merge', () => false);

    expect(result.ok).toBe(false);
    if (result.ok) return;
    expect(result.message).toContain('could not be saved');
    expect(current.map((item) => item.id)).toEqual(['existing']);
  });
});
